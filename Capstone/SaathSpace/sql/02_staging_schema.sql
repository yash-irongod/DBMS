-- Raw landing table for the supplied CSV files.
-- Run while connected to the `saathspace` database.
-- Keep raw source fields as text; transform into typed app tables separately.

BEGIN;
CREATE SCHEMA IF NOT EXISTS staging;

CREATE TABLE IF NOT EXISTS staging.rental_listings_raw (
    staging_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_file        VARCHAR(255) NOT NULL DEFAULT 'unassigned.csv',
    source_row_number  BIGINT,
    import_batch       VARCHAR(100) NOT NULL DEFAULT 'initial',
    imported_at        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    house_type         TEXT,
    house_size         TEXT,
    location           TEXT,
    city               TEXT,
    latitude           TEXT,
    longitude          TEXT,
    price              TEXT,
    currency           TEXT,
    num_bathrooms      TEXT,
    num_balconies      TEXT,
    is_negotiable      TEXT,
    price_sq_ft        TEXT,
    verification_date  TEXT,
    description        TEXT,
    security_deposit   TEXT,
    furnishing_status  TEXT
);

CREATE INDEX IF NOT EXISTS ix_staging_city ON staging.rental_listings_raw(city);
CREATE INDEX IF NOT EXISTS ix_staging_source_file ON staging.rental_listings_raw(source_file);

COMMIT;

-- Import-ready combined file is included at data/processed/rental_listings_staging.csv.
