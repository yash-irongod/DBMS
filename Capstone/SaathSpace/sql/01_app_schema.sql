-- SaathSpace application schema — first draft (PostgreSQL 18.x)
-- Run while connected to the `saathspace` database.

BEGIN;
CREATE SCHEMA IF NOT EXISTS app;

CREATE TABLE IF NOT EXISTS app.city (
    city_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_name    VARCHAR(100) NOT NULL UNIQUE,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT city_name_not_blank CHECK (BTRIM(city_name) <> '')
);

CREATE TABLE IF NOT EXISTS app.locality (
    locality_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_id       BIGINT NOT NULL REFERENCES app.city(city_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    locality_name VARCHAR(150) NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT locality_name_not_blank CHECK (BTRIM(locality_name) <> ''),
    CONSTRAINT uq_locality_city_name UNIQUE (city_id, locality_name)
);

CREATE TABLE IF NOT EXISTS app.app_user (
    user_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name     VARCHAR(120) NOT NULL,
    email         VARCHAR(254) NOT NULL UNIQUE,
    password_hash TEXT,
    account_role  VARCHAR(20) NOT NULL DEFAULT 'member'
                  CHECK (account_role IN ('member', 'admin')),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT full_name_not_blank CHECK (BTRIM(full_name) <> ''),
    CONSTRAINT email_not_blank CHECK (BTRIM(email) <> '')
);

CREATE TABLE IF NOT EXISTS app.listing (
    listing_id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id          BIGINT REFERENCES app.app_user(user_id) ON UPDATE CASCADE ON DELETE SET NULL,
    locality_id            BIGINT NOT NULL REFERENCES app.locality(locality_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    title                  VARCHAR(180) NOT NULL,
    listing_kind           VARCHAR(24) NOT NULL DEFAULT 'entire_unit'
                           CHECK (listing_kind IN ('entire_unit', 'private_room', 'shared_room', 'pg_hostel', 'other')),
    source_property_type   VARCHAR(120),
    rent_amount            NUMERIC(12,2) NOT NULL CHECK (rent_amount > 0),
    rent_period            VARCHAR(16) NOT NULL DEFAULT 'unknown'
                           CHECK (rent_period IN ('monthly', 'weekly', 'daily', 'unknown')),
    security_deposit       NUMERIC(12,2) CHECK (security_deposit IS NULL OR security_deposit >= 0),
    size_sqft              NUMERIC(10,2) CHECK (size_sqft IS NULL OR size_sqft > 0),
    bedrooms               SMALLINT CHECK (bedrooms IS NULL OR bedrooms >= 0),
    bathrooms              SMALLINT CHECK (bathrooms IS NULL OR bathrooms >= 0),
    balconies              SMALLINT CHECK (balconies IS NULL OR balconies >= 0),
    furnishing_status      VARCHAR(24) NOT NULL DEFAULT 'unknown'
                           CHECK (furnishing_status IN ('furnished', 'semi_furnished', 'unfurnished', 'unknown')),
    description            TEXT,
    latitude               NUMERIC(9,6),
    longitude              NUMERIC(9,6),
    availability_status    VARCHAR(20) NOT NULL DEFAULT 'unverified'
                           CHECK (availability_status IN ('available', 'unavailable', 'reserved', 'unverified', 'inactive')),
    data_origin            VARCHAR(24) NOT NULL DEFAULT 'user_submitted'
                           CHECK (data_origin IN ('public_dataset', 'user_submitted', 'synthetic_demo')),
    source_file            VARCHAR(255),
    source_row_number      BIGINT,
    last_verified_at       TIMESTAMPTZ,
    created_at             TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at             TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT listing_title_not_blank CHECK (BTRIM(title) <> ''),
    CONSTRAINT listing_lat_lon_valid CHECK (
        (latitude IS NULL AND longitude IS NULL)
        OR (latitude IS NOT NULL AND longitude IS NOT NULL
            AND latitude BETWEEN -90 AND 90 AND longitude BETWEEN -180 AND 180)
    )
);

CREATE TABLE IF NOT EXISTS app.amenity (
    amenity_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amenity_name VARCHAR(80) NOT NULL UNIQUE,
    CONSTRAINT amenity_name_not_blank CHECK (BTRIM(amenity_name) <> '')
);

CREATE TABLE IF NOT EXISTS app.listing_amenity (
    listing_id BIGINT NOT NULL REFERENCES app.listing(listing_id) ON UPDATE CASCADE ON DELETE CASCADE,
    amenity_id BIGINT NOT NULL REFERENCES app.amenity(amenity_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    PRIMARY KEY (listing_id, amenity_id)
);

CREATE TABLE IF NOT EXISTS app.roommate_profile (
    user_id                  BIGINT PRIMARY KEY REFERENCES app.app_user(user_id) ON UPDATE CASCADE ON DELETE CASCADE,
    preferred_city_id        BIGINT REFERENCES app.city(city_id) ON UPDATE CASCADE ON DELETE SET NULL,
    budget_min               NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (budget_min >= 0),
    budget_max               NUMERIC(12,2) NOT NULL CHECK (budget_max >= 0),
    move_in_date             DATE,
    food_preference          VARCHAR(24) NOT NULL DEFAULT 'no_preference'
                             CHECK (food_preference IN ('vegetarian', 'non_vegetarian', 'vegan', 'no_preference')),
    smoking_preference       VARCHAR(24) NOT NULL DEFAULT 'no_preference'
                             CHECK (smoking_preference IN ('non_smoker_only', 'okay_with_smoker', 'no_preference')),
    pets_preference          VARCHAR(24) NOT NULL DEFAULT 'no_preference'
                             CHECK (pets_preference IN ('no_pets', 'pets_ok', 'no_preference')),
    sleep_schedule           VARCHAR(24) NOT NULL DEFAULT 'no_preference'
                             CHECK (sleep_schedule IN ('early', 'regular', 'late', 'no_preference')),
    cleanliness_preference   VARCHAR(24) NOT NULL DEFAULT 'no_preference'
                             CHECK (cleanliness_preference IN ('relaxed', 'average', 'very_clean', 'no_preference')),
    updated_at               TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT roommate_budget_range_valid CHECK (budget_min <= budget_max)
);

CREATE TABLE IF NOT EXISTS app.saved_listing (
    user_id    BIGINT NOT NULL REFERENCES app.app_user(user_id) ON UPDATE CASCADE ON DELETE CASCADE,
    listing_id BIGINT NOT NULL REFERENCES app.listing(listing_id) ON UPDATE CASCADE ON DELETE CASCADE,
    saved_at   TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, listing_id)
);

CREATE TABLE IF NOT EXISTS app.enquiry (
    enquiry_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT NOT NULL REFERENCES app.app_user(user_id) ON UPDATE CASCADE ON DELETE CASCADE,
    listing_id     BIGINT NOT NULL REFERENCES app.listing(listing_id) ON UPDATE CASCADE ON DELETE CASCADE,
    message        TEXT NOT NULL,
    enquiry_status VARCHAR(20) NOT NULL DEFAULT 'new'
                   CHECK (enquiry_status IN ('new', 'responded', 'closed', 'withdrawn')),
    created_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT enquiry_message_not_blank CHECK (BTRIM(message) <> '')
);

CREATE TABLE IF NOT EXISTS app.roommate_request (
    request_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requester_user_id  BIGINT NOT NULL REFERENCES app.app_user(user_id) ON UPDATE CASCADE ON DELETE CASCADE,
    recipient_user_id  BIGINT NOT NULL REFERENCES app.app_user(user_id) ON UPDATE CASCADE ON DELETE CASCADE,
    message            TEXT,
    request_status     VARCHAR(20) NOT NULL DEFAULT 'pending'
                       CHECK (request_status IN ('pending', 'accepted', 'declined', 'cancelled')),
    created_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT roommate_request_not_self CHECK (requester_user_id <> recipient_user_id),
    CONSTRAINT uq_roommate_request_direction UNIQUE (requester_user_id, recipient_user_id)
);

-- First-pass indexes for common filters and joins.
CREATE INDEX IF NOT EXISTS ix_locality_city_id ON app.locality(city_id);
CREATE INDEX IF NOT EXISTS ix_listing_locality_id ON app.listing(locality_id);
CREATE INDEX IF NOT EXISTS ix_listing_rent_amount ON app.listing(rent_amount);
CREATE INDEX IF NOT EXISTS ix_listing_availability ON app.listing(availability_status);
CREATE INDEX IF NOT EXISTS ix_listing_kind ON app.listing(listing_kind);
CREATE INDEX IF NOT EXISTS ix_listing_owner_user_id ON app.listing(owner_user_id);
CREATE INDEX IF NOT EXISTS ix_enquiry_listing_created ON app.enquiry(listing_id, created_at DESC);
CREATE INDEX IF NOT EXISTS ix_roommate_profile_city_budget ON app.roommate_profile(preferred_city_id, budget_min, budget_max);
CREATE INDEX IF NOT EXISTS ix_roommate_request_recipient_status ON app.roommate_request(recipient_user_id, request_status);

COMMIT;
